def get_txt(lang_code: str, key: str) -> str:
    """Retrieve UI string in selected regional language with English fallback."""
    try:
        lang_dict = TRANSLATIONS.get(lang_code, TRANSLATIONS.get("en", {}))
        val = lang_dict.get(key)
        if not val:
            val = TRANSLATIONS.get("en", {}).get(key, key)
        return str(val)
    except Exception:
        return str(TRANSLATIONS.get("en", {}).get(key, key))

def translate_content_label(label: str, category: str, lang_code: str) -> str:
    """Translate dynamic content values (risk level, sif label, LSR tags) into selected regional language."""
    if lang_code == "en" or not label:
        return label

    if category == "risk_level":
        return RISK_LEVEL_MAP.get(label, {}).get(lang_code, label)
    elif category == "sif_label":
        return SIF_LABEL_MAP.get(label, {}).get(lang_code, label)
    elif category == "lsr":
        translated_rules = []
        for r in str(label).split('; '):
            tr = LSR_MAP.get(r, {}).get(lang_code, r)
            translated_rules.append(tr)
        return "; ".join(translated_rules)
    return label
